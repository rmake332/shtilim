/**
 * מספרי זיהוי "ממלא מקום" - מספר שהוקלד כשהמספר האמיתי לא היה ידוע, ואינו מזהה אף אחד.
 *
 * הכי חשוב: "000000000" **עובר** את חישוב הצ'קסאם של ת.ז. ישראלית (סכום של אפסים הוא 0,
 * ו-0 מתחלק ב-10), ולכן נחשב בעבר ת.ז. תקינה. כך נוצרו 16 רשומות עובד עם המספר הזה,
 * וגרוע מכך - הקלדתו בטופס התאימה לאחת מהן ובחרה אוטומטית אדם אקראי, כך שתקן חדש
 * היה נוצר על עובד לא קשור. לכן הפסילה חלה גם על התאמת ת.ז. מול איירטייבל
 * (`buildTzExactMatchFormula`) ולא רק על הקלט בטופס.
 *
 * הפסילה היא על ערך שכל תוויו זהים (000000000, 1111, AAAA) - משפחה שאין בה מספר זיהוי
 * לגיטימי, בישראלי או בזר. אין לפסול כאן מספרים קצרים: לת.ז. ישראלית לגיטימית יכולים
 * להיות אפסים מובילים (למשל 014373658), והריפוד נעשה ב-normalizeIsraeliId.
 */
export function isPlaceholderId(input: string): boolean {
  const cleaned = String(input).trim().replace(/[\s-]/g, '').toUpperCase();
  if (!cleaned) return true;
  return /^(.)\1*$/.test(cleaned);
}
